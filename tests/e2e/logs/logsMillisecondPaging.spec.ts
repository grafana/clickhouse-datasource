import { expect, test } from '@grafana/plugin-e2e';
import { Page, Response } from '@playwright/test';
import { pluginVersion } from '../../../src/utils/version';
import { DATASOURCE_UID, FIXTURE_FROM_ISO, FIXTURE_TO_ISO, PLUGIN_TYPE, skipFixtureTestsOnCloud } from '../helpers/env';
import { frameValues } from '../helpers/queryResponse';

// Eight rows share one second (tests/fixtures/logs_ms_paging.sql). A logs page of 3 ends mid-second, and the
// next page moves its end to the oldest row of the previous one. The seconds-precision `TimestampTime` range
// filter rounds up to the whole second, so on its own it would return the same newest rows again. The
// millisecond bound the logs query builder adds on the DateTime64 time column must move the page forward and
// repeat only the boundary row.
//
// The SQL is generated by the Logs query builder from its options (no hand-written SQL), so the spec fails when
// the builder stops emitting the millisecond bound.

const TARGET = {
  refId: 'A',
  datasource: { type: PLUGIN_TYPE, uid: DATASOURCE_UID },
  editorType: 'builder',
  pluginVersion,
  format: 2,
  queryType: 'logs',
  rawSql: '',
  builderOptions: {
    database: 'e2e_test',
    table: 'logs_ms_paging',
    queryType: 'logs',
    mode: 'list',
    columns: [
      { name: 'Timestamp', type: 'DateTime64(9)', hint: 'time' },
      { name: 'Body', type: 'String', hint: 'log_message' },
      // The coarse seconds-precision column the range filter prunes on.
      { name: 'TimestampTime', type: 'DateTime', hint: 'filter_time' },
    ],
    meta: {},
    limit: 3,
    filters: [
      {
        type: 'datetime',
        operator: 'WITH IN DASHBOARD TIME RANGE',
        filterType: 'custom',
        key: 'TimestampTime',
        hint: 'filter_time',
        condition: 'AND',
      },
    ],
    orderBy: [{ name: 'Timestamp', hint: 'time', dir: 'DESC', default: true }],
  },
};

function builderUrl(from: string, to: string): string {
  const panes = JSON.stringify({ explore: { datasource: DATASOURCE_UID, queries: [TARGET], range: { from, to } } });
  return `/explore?orgId=1&schemaVersion=1&panes=${encodeURIComponent(panes)}`;
}

function waitForMainQuery(page: Page): Promise<Response> {
  return page.waitForResponse(
    (r) => r.url().includes('/api/ds/query') && (r.request().postData() || '').includes('"refId":"A"')
  );
}

/** Open the Logs query builder on the target, run it, and return the builder-generated SQL and the Body values. */
async function runBuilderPage(page: Page, from: string, to: string) {
  const responsePromise = waitForMainQuery(page);
  await page.goto(builderUrl(from, to));
  await expect(page.getByRole('radio', { name: 'Query Builder' })).toBeChecked();
  const response = await responsePromise;
  expect(response.ok()).toBe(true);

  const sent = response
    .request()
    .postDataJSON()
    ?.queries?.find((q: { refId?: string }) => q.refId === 'A');
  return { rawSql: String(sent?.rawSql ?? ''), body: await response.json() };
}

test.describe('logs millisecond paging', () => {
  test.describe.configure({ mode: 'serial' });

  test.beforeEach(() => {
    skipFixtureTestsOnCloud('logs_ms_paging.sql');
  });

  test('the builder-generated next page moves past rows that share a second', async ({ page }) => {
    const first = await runBuilderPage(page, FIXTURE_FROM_ISO, FIXTURE_TO_ISO);
    expect(first.rawSql).toContain('$__toTime_ms');
    expect(frameValues(first.body)[1]).toEqual(['row-8', 'row-7', 'row-6']);

    // Page 2 ends at the oldest row of page 1 (10:00:00.600).
    const second = await runBuilderPage(page, FIXTURE_FROM_ISO, '2024-03-15T10:00:00.600Z');
    expect(second.rawSql).toContain('$__toTime_ms');
    expect(frameValues(second.body)[1]).toEqual(['row-6', 'row-5', 'row-4']);
  });
});
